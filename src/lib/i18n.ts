export function t(language: LanguageCode | undefined, key: I18nKey, values: Record<string, string | number> = {}): string {
  const dictionary = dictionaries[language ?? 'en'] ?? dictionaries.en;
  const template = dictionary[key] ?? dictionaries.en[key];
  return Object.entries(values).reduce(
    (message, [name, value]) => message.replaceAll(`{${name}}`, String(value)),
    template,
  );
}

export function isRtlLanguage(language: LanguageCode): boolean {
  return language === 'ar';
}
